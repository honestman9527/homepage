export type UiKey = keyof typeof ui;

export function uiText(key: UiKey, values: Record<string, string | number> = {}): string {
  return ui[key].replace(/\{(\w+)\}/g, (placeholder, name) =>
    String(values[name] ?? placeholder),
  );
}

export function formatDate(date: Date): string {
  return new Intl.DateTimeFormat("zh-CN", {
    year: "numeric",
    month: "long",
    day: "numeric",
    timeZone: "UTC",
  }).format(date);
}
